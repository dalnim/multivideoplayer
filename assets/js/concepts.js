const languageSelect = document.getElementById('language');
function resolveLanguage(value) {
 if (typeof value !== 'string') return null;
 const tag = value.trim().replace(/_/g, '-').toLowerCase();
 const exact = Object.keys(copy).find(language => language.toLowerCase() === tag);
 if (exact) return exact;
 const [base, ...subtags] = tag.split('-');
 if (base === 'zh') {
  if (subtags.includes('hant')) return 'zh-TW';
  if (subtags.includes('hans')) return 'zh-CN';
  return subtags.some(tag => ['tw', 'hk', 'mo'].includes(tag)) ? 'zh-TW' : 'zh-CN';
 }
 if (base === 'nb' || base === 'nn') return 'no';
 return Object.hasOwn(copy, base) ? base : null;
}
function getInitialLanguage() {
 try {
  const stored = resolveLanguage(localStorage.getItem('selectedLanguage'));
  if (stored) return stored;
 } catch {}
 const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
 for (const preferred of languages) {
  const language = resolveLanguage(preferred);
  if (language) return language;
 }
 return 'en';
}
